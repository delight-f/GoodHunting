#!/usr/bin/env python3
"""
Build the Good Hunting golden data + generated C# tables.

Source of truth: two engine dumps produced by the `spike/` probe mod running
against the real Vintage Story 1.22.7 server:
    tools/fixtures/vanilla_dump.json   (probe only)
    tools/fixtures/patched_dump.json   (probe + the legacy content-patch mod)

The *only* meaningful difference between the two is what the legacy mod changed,
so we diff them to extract exactly that data. This guarantees the ported C# tables
are byte-for-byte identical to the legacy mod's output at 1x (parity by construction).

Outputs:
    tools/golden_drops.json        committed golden fixture (changed subset)
    src/Data/GoodHuntingData.g.cs  generated C# tables

Re-run:  python3 tools/build_data.py
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIX = os.path.join(ROOT, "tools", "fixtures")
GOLDEN = os.path.join(ROOT, "tools", "golden_drops.json")
CS_OUT = os.path.join(ROOT, "src", "Data", "GoodHuntingData.g.cs")


def num(x):
    """Normalise to float or None."""
    return None if x is None else round(float(x), 6)


def drop(d) -> dict:
    return {
        "type": d.get("type", "item"),
        "code": d.get("code", ""),
        "avg": num(d.get("avg", 0)) or 0.0,
        "var": num(d.get("var", 0)) or 0.0,
    }


def build_golden() -> dict:
    vanilla = load(os.path.join(FIX, "vanilla_dump.json"))
    patched = load(os.path.join(FIX, "patched_dump.json"))

    entities = {}
    for code, pv in patched["entities"].items():
        vv = vanilla["entities"].get(code, {})
        entry: dict = {}

        p_drops = [drop(d) for d in pv.get("drops", [])]
        v_drops = [drop(d) for d in vv.get("drops", [])]
        if p_drops != v_drops:
            entry["drops"] = p_drops

        p_h = pv.get("health")
        v_h = vv.get("health")
        if p_h != v_h:
            # The engine resolves *ByType per expanded type, so the dump carries flat values.
            entry["health"] = {
                "max": health_value(p_h, code, "maxhealth"),
                "current": health_value(p_h, code, "currenthealth"),
            }

        if entry:
            entities[code] = entry

    fish = {}
    for code, pv in patched["fish"].items():
        vv = vanilla["fish"].get(code, [])
        p_list = [drop(d) for d in pv]
        if p_list != [drop(d) for d in vv]:
            fish[code] = p_list

    return {
        "_comment": "Generated by tools/build_data.py from the engine dumps. Do not hand-edit.",
        "entities": entities,
        "fish": fish,
    }


def load(path: str):
    with open(path) as fh:
        return json.load(fh)


def health_value(h, code: str, key: str) -> float:
    value = num((h or {}).get(key))
    if value is None:
        raise SystemExit(f"{code}: no resolved {key} in the patched dump")
    return value


def f(x) -> str:
    if x is None:
        raise ValueError("missing number")
    return f"{float(x):g}f"


def gen_csharp(golden: dict) -> str:
    lines = []
    a = lines.append
    a("// <auto-generated>")
    a("//   Generated by tools/build_data.py from the Vintage Story engine dumps in tools/fixtures/.")
    a("//   Do not edit by hand. Re-run: python3 tools/build_data.py")
    a("// </auto-generated>")
    a("#nullable enable")
    a("using System.Collections.Generic;")
    a("")
    a("namespace GoodHunting.Data;")
    a("")
    a("public static partial class GoodHuntingData")
    a("{")
    a(f"    // entity types with changed data: {len(golden['entities'])}")
    a(f"    // fish variants with changed data: {len(golden['fish'])}")
    a("")
    a("    public static readonly Dictionary<string, EntityEntry> Entities = new()")
    a("    {")
    for code, e in sorted(golden["entities"].items()):
        a(f"        [{cs(code)}] = new EntityEntry")
        a("        {")
        if "drops" in e:
            a("            DropsChanged = true,")
            a("            Drops = new DropSpec[]")
            a("            {")
            for d in e["drops"]:
                a(f"                new DropSpec {{ Type = {cs(d['type'])}, Code = {cs(d['code'])}, Avg = {f(d['avg'])}, Var = {f(d['var'])} }},")
            a("            },")
        if "health" in e:
            a("            HealthChanged = true,")
            h = e["health"]
            a(f"            MaxHealth = {f(h.get('max'))},")
            a(f"            CurrentHealth = {f(h.get('current'))},")
        a("        },")
    a("    };")
    a("")
    a("    public static readonly Dictionary<string, DropSpec[]> Fish = new()")
    a("    {")
    for code, drops in sorted(golden["fish"].items()):
        a(f"        [{cs(code)}] = new DropSpec[]")
        a("        {")
        for d in drops:
            a(f"            new DropSpec {{ Type = {cs(d['type'])}, Code = {cs(d['code'])}, Avg = {f(d['avg'])}, Var = {f(d['var'])} }},")
        a("        },")
    a("    };")
    a("}")
    return "\n".join(lines) + "\n"


def cs(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    golden = build_golden()
    with open(GOLDEN, "w") as fh:
        json.dump(golden, fh, indent=1, sort_keys=True)
        fh.write("\n")

    os.makedirs(os.path.dirname(CS_OUT), exist_ok=True)
    with open(CS_OUT, "w") as fh:
        fh.write(gen_csharp(golden))

    ne = len(golden["entities"])
    nf = len(golden["fish"])
    nd = sum(len(e.get("drops", [])) for e in golden["entities"].values())
    nh = sum(1 for e in golden["entities"].values() if "health" in e)
    fd = sum(len(v) for v in golden["fish"].values())
    print(f"golden: {ne} entity types ({nd} drop entries, {nh} health changes), {nf} fish variants ({fd} entries)")
    print(f"wrote {GOLDEN}")
    print(f"wrote {CS_OUT}")


if __name__ == "__main__":
    sys.exit(main())
